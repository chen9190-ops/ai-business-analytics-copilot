# Overall Sales Analysis
# ==========================================

def analyze_overall_sales(df, schema):

    sales_col = schema["sales"]

    profit_col = schema["profit"]

    order_col = schema.get("order")

    # --------------------------------------
    # Total Sales
    # --------------------------------------

    total_sales = (
        df[sales_col].sum()
        if sales_col is not None
        else None
    )

    # --------------------------------------
    # Total Profit
    # --------------------------------------

    if profit_col is not None:

        total_profit = df[profit_col].sum()

        profit_margin = (
            total_profit / total_sales
            if total_sales != 0
            else None
        )

    else:

        total_profit = "Not Available"

        profit_margin = "Not Available"

    # --------------------------------------
    # Average Order Value
    # --------------------------------------

    if order_col is not None:

        aov = (
            df[sales_col].sum() /
            df[order_col].nunique()
        )

    else:

        aov = "Not Available"

    # --------------------------------------
    # Return
    # --------------------------------------

    return {

        "total_sales": total_sales,

        "total_profit": total_profit,

        "profit_margin": profit_margin,

        "avg_order_value": aov
    }

