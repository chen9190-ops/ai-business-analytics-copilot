def detect_relevant_column(question, columns):

    prompt = f"""
    You are a data analyst.

    User Question:
    {question}

    Dataset Columns:
    {list(columns)}

    IMPORTANT:
    Return ONLY ONE exact column name.

    Do NOT explain.
    Do NOT use bullet points.
    Do NOT use sentences.
    Return ONLY the raw column name.
    """

    response = client.chat.completions.create(

        model="gpt-4.1-mini",

        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ]
    )

    return response.choices[0].message.content.strip()

