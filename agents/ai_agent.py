# ==========================================

def route_question(question, router_history):

    prompt = f"""

    You are an AI business analytics router.

    Your job is to choose the SINGLE best tool
    for answering the user's question.

    Available tools:

    1. analyze_overall_sales
       -> overall sales and profit summary

    2. analyze_monthly_sales_trend
       -> time trend and seasonality analysis

    3. analyze_discount_profit
       -> discount and profit relationship

    4. analyze_subcategory_profit
       -> category and sub-category profitability

    5. analyze_top_revenue_products
       -> top-selling products

    6. analyze_top_loss_products
       -> worst-performing products

    7. analyze_worst_region_products
       -> worst region-product combinations

    8. analyze_best_region_products
       -> best region-product combinations

    9. analyze_customer_segmentation
       -> customer segmentation analysis

    10. analyze_customer_clv
        -> customer lifetime value analysis

    11. analyze_segment_customer_type
        -> segment and customer type analysis

    12. train_customer_classifier
        -> machine learning prediction
           for high-value customers

    Return ONLY the tool name.

    User Question:
    {question}

    """


    router_history.append({

        "role": "user",

        "content": prompt
    })

    response = client.chat.completions.create(

        model="gpt-4.1-mini",

        messages=router_history
    )

    router_history.append({

        "role": "assistant",

        "content":
        response.choices[0].message.content
    })

    return response.choices[0].message.content.strip()


